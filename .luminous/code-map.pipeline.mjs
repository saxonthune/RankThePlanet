// code-map.pipeline.mjs — derive a compressed, agent-consumable code map from
// the Kotlin sources. See .rhidoc doc01.04.03 for the intent.
//
//   node .luminous/code-map.pipeline.mjs
//
// Parses every .kt file under SRC_ROOT with tree-sitter-kotlin and emits a
// signature skeleton (bodies stripped) to .luminous/generated/code-map.md.
// The generated tree is gitignored — edit code and re-run, never hand-edit.

import Parser from 'tree-sitter';
import Kotlin from 'tree-sitter-kotlin';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC_ROOT = join(REPO, 'app/composeApp/src');
const OUT = join(REPO, '.luminous/generated/code-map.md');

// --- 1. discover source files --------------------------------------------

function findKotlin(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    if (name === 'build') continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) findKotlin(full, acc);
    else if (name.endsWith('.kt')) acc.push(full);
  }
  return acc;
}

// --- 2. parse one file into a typed model --------------------------------

const parser = new Parser();
parser.setLanguage(Kotlin);

const BODY_KINDS = new Set(['class_body', 'enum_class_body', 'function_body']);

// Source slice from node start to its body (if any), whitespace-collapsed.
function header(node, src) {
  let end = node.endIndex;
  for (let i = 0; i < node.childCount; i++) {
    const c = node.child(i);
    if (BODY_KINDS.has(c.type)) { end = c.startIndex; break; }
  }
  return src.slice(node.startIndex, end).replace(/\s+/g, ' ').trim();
}

// A property header without its initializer — name and declared type survive.
function propHeader(node, src) {
  const text = header(node, src);
  const eq = text.indexOf(' = ');
  return (eq === -1 ? text : text.slice(0, eq)).trim();
}

// First sentence of a /** */ block sitting immediately above the node.
function kdoc(src, startIndex) {
  const before = src.slice(0, startIndex);
  const m = before.match(/\/\*\*([\s\S]*?)\*\/\s*$/);
  if (!m) return null;
  const body = m[1].replace(/^\s*\*\s?/gm, '').trim();
  const firstLine = body.split('\n').find((l) => l.trim());
  return firstLine ? firstLine.trim() : null;
}

function nameOf(node) {
  const id = node.childForFieldName?.('name')
    ?? node.namedChildren.find((c) => c.type === 'type_identifier' || c.type === 'simple_identifier');
  return id ? id.text : '(anonymous)';
}

function modifierText(node) {
  const mods = node.namedChildren.find((c) => c.type === 'modifiers');
  return mods ? mods.text : '';
}

// Member kinds we surface inside a class/interface/object body.
function members(bodyNode, src) {
  if (!bodyNode) return [];
  const out = [];
  for (const c of bodyNode.namedChildren) {
    if (modifierText(c).includes('private')) continue;
    if (c.type === 'function_declaration') {
      out.push({ kind: 'fun', name: nameOf(c), sig: header(c, src) });
    } else if (c.type === 'property_declaration') {
      out.push({ kind: 'prop', name: nameOf(c), sig: propHeader(c, src) });
    } else if (c.type === 'class_declaration' || c.type === 'object_declaration') {
      out.push({ kind: 'nested', name: nameOf(c), sig: header(c, src) });
    }
  }
  return out;
}

function parseFile(path, src) {
  const root = parser.parse(src, undefined, { bufferSize: src.length + 1 }).rootNode;
  const pkgNode = root.namedChildren.find((c) => c.type === 'package_header');
  const pkg = pkgNode ? pkgNode.text.replace(/^package\s+/, '').trim() : '(default)';

  const decls = [];
  for (const node of root.namedChildren) {
    const isType = node.type === 'class_declaration' || node.type === 'object_declaration';
    const isFn = node.type === 'function_declaration';
    const isProp = node.type === 'property_declaration';
    if (!isType && !isFn && !isProp) continue;
    if (modifierText(node).includes('private')) continue;

    const body = node.namedChildren.find((c) => c.type === 'class_body' || c.type === 'enum_class_body');
    decls.push({
      kind: isFn ? 'fun' : isProp ? 'prop' : 'type',
      name: nameOf(node),
      sig: isProp ? propHeader(node, src) : header(node, src),
      doc: kdoc(src, node.startIndex),
      members: members(body, src),
    });
  }
  return { path, pkg, decls };
}

// --- 3. render the model to Markdown -------------------------------------

function render(files) {
  const byPkg = new Map();
  for (const f of files) {
    if (!byPkg.has(f.pkg)) byPkg.set(f.pkg, []);
    byPkg.get(f.pkg).push(f);
  }

  const lines = [
    '# RTP Code Map',
    '',
    '_Generated by `.luminous/code-map.pipeline.mjs` from `app/composeApp/src`._',
    '_A signature skeleton — bodies stripped. Do not edit; re-run the pipeline._',
    '',
    `_${files.length} files, ${files.reduce((n, f) => n + f.decls.length, 0)} top-level declarations._`,
    '',
  ];

  for (const pkg of [...byPkg.keys()].sort()) {
    lines.push(`## ${pkg}`, '');
    for (const f of byPkg.get(pkg).sort((a, b) => a.path.localeCompare(b.path))) {
      lines.push(`### ${relative(REPO, f.path)}`, '');
      for (const d of f.decls) {
        if (d.doc) lines.push(`_${d.doc}_`);
        lines.push('```kotlin', d.sig, '```');
        for (const m of d.members) lines.push(`- \`${m.sig}\``);
        lines.push('');
      }
    }
  }
  return lines.join('\n');
}

// --- 4. main -------------------------------------------------------------

const paths = findKotlin(SRC_ROOT).sort();
const files = paths.map((p) => parseFile(p, readFileSync(p, 'utf8')));
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, render(files));
console.log(`code-map: ${files.length} files -> ${relative(REPO, OUT)}`);
